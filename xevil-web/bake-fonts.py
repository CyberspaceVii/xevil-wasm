#!/usr/bin/env python3
"""Bake the X.org misc-misc BDF fonts XEvil asks for (6x13 regular, 9x15B as the
'big' helvetica-18 stand-in) into xfonts.h: fixed cells, ASCII 32..126, one
uint16 per scanline, MSB = leftmost pixel. Fonts are public domain
(font-misc-misc COPYING: "Public domain font.  Share and enjoy.").

usage: bake-fonts.py <out.h> name=path.bdf [name=path.bdf ...]
"""
import sys


def parse_bdf(path):
    ascent = descent = None
    bbw = bbh = 0
    glyphs = {}
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for ln in lines:
        k, _, v = ln.partition(" ")
        if k == "FONTBOUNDINGBOX":
            bbw, bbh = map(int, v.split()[:2])
        elif k == "FONT_ASCENT":
            ascent = int(v)
        elif k == "FONT_DESCENT":
            descent = int(v)
        elif k == "STARTCHAR":
            enc, bbx, bits = None, None, []
            for g in lines:
                gk, _, gv = g.partition(" ")
                if gk == "ENCODING":
                    enc = int(gv.split()[0])
                elif gk == "BBX":
                    bbx = tuple(map(int, gv.split()))
                elif gk == "BITMAP":
                    for b in lines:
                        if b == "ENDCHAR":
                            break
                        bits.append(int(b, 16) << (16 - 4 * len(b)) & 0xFFFF)
                    break
            if enc is not None and 32 <= enc <= 126:
                glyphs[enc] = (bbx, bits)
    assert ascent is not None and descent is not None
    h = ascent + descent
    out = {}
    for c in range(32, 127):
        rows = [0] * h
        if c in glyphs:
            (gw, gh, gx, gy), bits = glyphs[c]
            top = ascent - (gy + gh)  # glyph's first row, measured from cell top
            for i, r in enumerate(bits):
                y = top + i
                if 0 <= y < h:
                    rows[y] = (r >> gx) if gx >= 0 else (r << -gx) & 0xFFFF
        out[c] = rows
    return bbw, ascent, descent, out


def main():
    dst, specs = sys.argv[1], sys.argv[2:]
    o = ["/* Generated by bake-fonts.py from X.org font-misc-misc BDFs (public domain). */",
         "#ifndef C7_XFONTS_H", "#define C7_XFONTS_H", "#include <stdint.h>", ""]
    for spec in specs:
        name, path = spec.split("=", 1)
        w, a, d, g = parse_bdf(path)
        h = a + d
        o.append(f"#define XF_{name.upper()}_W {w}")
        o.append(f"#define XF_{name.upper()}_ASC {a}")
        o.append(f"#define XF_{name.upper()}_DESC {d}")
        o.append(f"static const uint16_t xf_{name}[95][{h}] = {{")
        for c in range(32, 127):
            o.append("  {" + ",".join(f"0x{r:04x}" for r in g[c]) + "},")
        o.append("};\n")
    o.append("#endif")
    with open(dst, "w") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
